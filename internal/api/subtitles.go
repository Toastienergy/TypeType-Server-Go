// subtitles is YouTubeSubtitleDeliveryService: a track is picked from the token service inventory, then from the
// stream's own captions; VTT comes through the token service, TTML straight from YouTube. Results are kept six hours
// (five seconds for a live) in memory and under the Kotlin Dragonfly key.
type subtitles struct {
	s        *Server
	mu       sync.Mutex
	inflight map[string]chan struct{}
	memory   map[string]subtitleEntry
	permits  chan struct{}
	client   *http.Client
}

type subtitleEntry struct {
	Content string `json:"content"`
	IsLive  bool   `json:"isLive"`
	at      time.Time
}

type subtitleSel struct {
	videoID, language, variant, format, source, translation, name string
	viewer                                                        string
}

const maxSubtitleBytes = 5 << 20

func newSubtitles(s *Server) *subtitles {
	return &subtitles{s: s, inflight: map[string]chan struct{}{}, memory: map[string]subtitleEntry{}, permits: make(chan struct{}, 64),
		client: &http.Client{Timeout: 30 * time.Second}}
}

func (sel subtitleSel) key() string {
	raw := strings.Join([]string{sel.videoID, strings.ToLower(sel.language), sel.variant, sel.format, strings.ToLower(sel.source),
		strings.ToLower(sel.translation), sel.name}, ":")
	if _, signedIn := requiresSession.Load(sel.videoID); signedIn {
		raw += ":" + sel.viewer
	}
	sum := sha256.Sum256([]byte(raw))
	return "youtube-subtitle:v1:" + hex.EncodeToString(sum[:])
}

func validTag(v string) bool {
	if v == "" || len(v) > 64 {
		return false
	}
	for _, r := range v {
		if !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || strings.ContainsRune("-_.", r)) {
			return false
		}
	}
	return true
}

func validPayload(b []byte, format string) bool {
	if len(b) == 0 || len(b) > maxSubtitleBytes {
		return false
	}
	t := strings.TrimLeft(string(b[:min(len(b), 64)]), " \t\r\n\uFEFF")
	if format == "vtt" {
		return strings.HasPrefix(t, "WEBVTT")
	}
	return strings.HasPrefix(t, "<?xml") || strings.HasPrefix(t, "<tt")
}

func (st *subtitles) cached(ctx context.Context, sel subtitleSel) (subtitleEntry, bool) {
	k := sel.key()
	st.mu.Lock()
	e, ok := st.memory[k]
	st.mu.Unlock()
	ttl := 6 * time.Hour
	if e.IsLive {
		ttl = 5 * time.Second
	}
	if ok && time.Since(e.at) < ttl {
		return e, true
	}
	v, ok, _ := st.s.Cache.Get(ctx, k)
	if !ok || json.Unmarshal([]byte(v), &e) != nil || !validPayload([]byte(e.Content), sel.format) {
		return subtitleEntry{}, false
	}
	e.at = time.Now()
	st.remember(k, e)
	return e, true
}

func (st *subtitles) remember(k string, e subtitleEntry) {
	st.mu.Lock()
	defer st.mu.Unlock()
	if len(st.memory) >= 160 {
		for old, oe := range st.memory {
			if time.Since(oe.at) > 5*time.Minute || len(st.memory) >= 160 {
				delete(st.memory, old)
			}
		}
	}
	st.memory[k] = e
}

func (st *subtitles) inventory(ctx context.Context, id string) []youtube.Subtitle {
	req, _ := http.NewRequestWithContext(ctx, "GET", st.s.Cfg.SubtitleService+"/subtitles?videoId="+id, nil)
	res, err := st.client.Do(req)
	if err != nil {
		return nil
	}
	defer res.Body.Close()
	var out []youtube.Subtitle
	if res.StatusCode != http.StatusOK || json.NewDecoder(io.LimitReader(res.Body, 4<<20)).Decode(&out) != nil {
		return nil
	}
	return out
}

func timedText(raw string) (*url.URL, bool) {
	u, err := url.Parse(raw)
	if err != nil || u.Scheme != "https" || u.Path != "/api/timedtext" {
		return nil, false
	}
	h := u.Hostname()
	return u, h == "youtube.com" || strings.HasSuffix(h, ".youtube.com")
}

// trackURL is the matching track's timedtext URL in the requested format and translation, or "".
func trackURL(tracks []youtube.Subtitle, sel subtitleSel) string {
	for _, t := range tracks {
		u, _ := url.Parse(t.URL)
		var q url.Values
		if u != nil {
			q = u.Query()
		}
		src := t.LanguageTag
		if q.Has("lang") {
			src = q.Get("lang")
		}
		want := sel.source
		if want == "" {
			want = sel.language
		}
		if !strings.EqualFold(src, want) && !strings.EqualFold(t.LanguageTag, sel.language) {
			continue
		}
		auto := t.IsAutoGenerated || q.Get("kind") == "asr" || strings.HasPrefix(q.Get("vssId"), "a.")
		if auto != (sel.variant == "auto") || sel.name != "" && q.Get("name") != sel.name {
			continue
		}
		tu, ok := timedText(t.URL)
		if !ok {
			return ""
		}
		tq := tu.Query()
		tq.Set("fmt", sel.format)
		if sel.translation == "" {
			tq.Del("tlang")
		} else {
			tq.Set("tlang", sel.translation)
		}
		tu.RawQuery = tq.Encode()
		return tu.String()
	}
	return ""
}

type fetchOutcome int

const (
	subReady fetchOutcome = iota
	subExpired
	subThrottled
	subInvalid
	subUnavailable
	subNotFound
)

func (st *subtitles) fetchTrack(ctx context.Context, track, format string) ([]byte, fetchOutcome) {
	target := track
	if format == "vtt" {
		target = st.s.Cfg.SubtitleService + "/subtitles/content?url=" + url.QueryEscape(track)
	}
	req, _ := http.NewRequestWithContext(ctx, "GET", target, nil)
	ctype := map[string]string{"vtt": "text/vtt; charset=utf-8", "ttml": "application/ttml+xml; charset=utf-8"}[format]
	if format == "vtt" {
		req.Header.Set("Accept", ctype)
	} else {
		req.Header.Set("Accept", ctype+",*/*;q=0.8")
		req.Header.Set("Origin", "https://m.youtube.com")
		req.Header.Set("Referer", "https://m.youtube.com/")
		req.Header.Set("User-Agent", youtube.Web.UA)
	}
	if id := httpx.RequestID(ctx); id != "" {
		req.Header.Set("X-Request-ID", id)
	}
	res, err := st.client.Do(req)
	if err != nil {
		return nil, subUnavailable
	}
	defer res.Body.Close()
	switch {
	case res.StatusCode == 429:
		return nil, subThrottled
	case res.StatusCode == 403 || res.StatusCode == 404 || res.StatusCode == 410:
		return nil, subExpired
	case res.StatusCode/100 != 2:
		return nil, subUnavailable
	}
	b, err := io.ReadAll(io.LimitReader(res.Body, maxSubtitleBytes+1))
	if err != nil {
		return nil, subUnavailable
	}
	if !validPayload(bytes.Clone(b), format) {
		return nil, subInvalid
	}
	return b, subReady
}

