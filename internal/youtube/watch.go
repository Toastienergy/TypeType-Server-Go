type Chapter struct {
	Title            string  `json:"title"`
	StartTimeSeconds int     `json:"startTimeSeconds"`
	ChannelName      *string `json:"channelName"`
	URL              *string `json:"url"`
	PreviewURL       *string `json:"previewUrl"`
}

type Subtitle struct {
	URL                 string `json:"url"`
	MimeType            string `json:"mimeType"`
	LanguageTag         string `json:"languageTag"`
	DisplayLanguageName string `json:"displayLanguageName"`
	IsAutoGenerated     bool   `json:"isAutoGenerated"`
}

type Frames struct {
	URLs             []string `json:"urls"`
	FrameWidth       int      `json:"frameWidth"`
	FrameHeight      int      `json:"frameHeight"`
	TotalCount       int      `json:"totalCount"`
	DurationPerFrame int      `json:"durationPerFrame"`
	FramesPerPageX   int      `json:"framesPerPageX"`
	FramesPerPageY   int      `json:"framesPerPageY"`
}

// Watch is everything the video page shows apart from the media formats.
type Watch struct {
	ID, Title, Description          string
	UploaderName, UploaderURL       string
	UploaderAvatarURL, ThumbnailURL string
	Duration, ViewCount, LikeCount  int64
	Subscribers                     int64
	Verified, Unlisted, LiveContent bool
	Live, Short                     bool
	UploadDate                      string
	Uploaded                        int64
	Category, License               string
	Tags                            []string
	Chapters                        []Chapter
	Subtitles                       []Subtitle
	Frames                          []Frames
	Related                         []VideoItem
	RelatedContinuation             string
	PlayableReason                  string
	Playable                        bool
}

// FetchWatch asks the WEB player and next endpoints at once; the page needs both and neither waits for the other.
func (c *Client) FetchWatch(ctx context.Context, id string) (*Watch, error) {
	type res struct {
		v   map[string]any
		err error
	}
	pc, vc, nc := make(chan res, 1), make(chan res, 1), make(chan res, 1)
	call := func(ch chan res, ci ClientInfo, endpoint string) {
		v, err := c.Call(ctx, ci, endpoint, map[string]any{"videoId": id, "contentCheckOk": true, "racyCheckOk": true})
		ch <- res{v, err}
	}
	go call(pc, Web, "player")
	go call(vc, AndroidVR, "player")
	go call(nc, Web, "next")
	p, vr, n := <-pc, <-vc, <-nc
	if p.err != nil && vr.err != nil {
		return nil, p.err
	}
	// The WEB player keeps the microformat (dates, category, likes) even when it refuses to play, but drops the
	// storyboards and captions with it; the ANDROID_VR player still carries both.
	base := p.v
	if base == nil {
		base = vr.v
	}
	w := parsePlayer(id, base)
	if vr.err == nil && vr.v != nil {
		if len(w.Frames) == 0 {
			w.Frames = parseFrames(vr.v)
		}
		if len(w.Subtitles) == 0 {
			w.Subtitles = parseCaptions(vr.v)
		}
		if w.Title == "" {
			w.Title = Str(vr.v, "videoDetails", "title")
		}
	}
	if n.err == nil {
		parseNext(w, n.v, time.Now())
		c.rememberComments(id, commentsToken(n.v))
	}
	return w, nil
}

func parsePlayer(id string, p map[string]any) *Watch {
	vd := Obj(p, "videoDetails")
	mf := Obj(p, "microformat", "playerMicroformatRenderer")
	w := &Watch{ID: id, Title: Str(vd, "title"), Description: Str(vd, "shortDescription"), UploaderName: Str(vd, "author"),
		ViewCount: -1, LikeCount: -1, Subscribers: -1, Uploaded: -1}
	if w.Title == "" {
		w.Title = Text(mf["title"])
	}
	if w.Description == "" {
		w.Description = Text(mf["description"])
	}
	if cid := Str(vd, "channelId"); cid != "" {
		w.UploaderURL = ChannelURL(cid)
	}
	w.ThumbnailURL = LastURL(List(vd, "thumbnail", "thumbnails"))
	w.Duration, _ = strconv.ParseInt(Str(vd, "lengthSeconds"), 10, 64)
	if v, err := strconv.ParseInt(Str(vd, "viewCount"), 10, 64); err == nil {
		w.ViewCount = v
	}
	if Bool(vd, "allowRatings") {
		if v, err := strconv.ParseInt(Str(mf, "likeCount"), 10, 64); err == nil {
			w.LikeCount = v
		}
	} else if vd != nil {
		w.LikeCount = -1
	}
	for _, k := range List(vd, "keywords") {
		if s, ok := k.(string); ok {
			w.Tags = append(w.Tags, s)
		}
	}
	w.LiveContent, w.Live = Bool(vd, "isLiveContent"), Bool(vd, "isLive")
	w.Unlisted = Bool(mf, "isUnlisted")
	w.Category = Str(mf, "category")
	live := Obj(mf, "liveBroadcastDetails")
	for _, k := range []string{Str(live, "endTimestamp"), Str(live, "startTimestamp"), Str(mf, "uploadDate"), Str(mf, "publishDate")} {
		if k != "" {
			w.UploadDate = k
			break
		}
	}
	if t, ok := ParseDate(w.UploadDate); ok {
		w.Uploaded = t.UnixMilli()
	}
	w.Playable = Str(p, "playabilityStatus", "status") == "OK"
	w.PlayableReason = Str(p, "playabilityStatus", "reason")
	w.Frames = parseFrames(p)
	w.Subtitles = parseCaptions(p)
	return w
}

func parseFrames(p map[string]any) []Frames {
	sb := Obj(p, "storyboards")
	r := Obj(sb, "playerLiveStoryboardSpecRenderer")
	if r == nil {
		r = Obj(sb, "playerStoryboardSpecRenderer")
	}
	spec := Str(r, "spec")
	if spec == "" {
		return []Frames{}
	}
	parts := strings.Split(spec, "|")
	out := []Frames{}
	for i := 1; i < len(parts); i++ {
		f := strings.Split(parts[i], "#")
		if len(f) != 8 {
			continue
		}
		n := make([]int, 6)
		bad := false
		for j := 0; j < 6; j++ {
			v, err := strconv.Atoi(f[j])
			if err != nil {
				bad = true
			}
			n[j] = v
		}
		if bad || n[5] == 0 {
			continue
		}
		base := strings.ReplaceAll(strings.ReplaceAll(parts[0], "$L", strconv.Itoa(i-1)), "$N", f[6]) + "&sigh=" + f[7]
		urls := []string{base}
		if strings.Contains(base, "$M") {
			per := n[3] * n[4]
			pages := (n[2] + per - 1) / max(per, 1)
			urls = make([]string, 0, pages)
			for j := 0; j < pages; j++ {
				urls = append(urls, strings.ReplaceAll(base, "$M", strconv.Itoa(j)))
			}
		}
		out = append(out, Frames{URLs: urls, FrameWidth: n[0], FrameHeight: n[1], TotalCount: n[2], DurationPerFrame: n[5],
			FramesPerPageX: n[3], FramesPerPageY: n[4]})
	}
	return out
}

var fmtParam = regexp.MustCompile(`&fmt=[^&]*`)
var tlangParam = regexp.MustCompile(`&tlang=[^&]*`)

func parseCaptions(p map[string]any) []Subtitle {
	out := []Subtitle{}
	for _, t := range List(p, "captions", "playerCaptionsTracklistRenderer", "captionTracks") {
		code, base, vss := Str(t, "languageCode"), Str(t, "baseUrl"), Str(t, "vssId")
		if code == "" || base == "" || vss == "" {
			continue
		}
		if strings.HasPrefix(base, "/") {
			base = "https://www.youtube.com" + base
		}
		base = tlangParam.ReplaceAllString(fmtParam.ReplaceAllString(base, ""), "")
		out = append(out, Subtitle{URL: base + "&fmt=ttml", MimeType: "application/ttml+xml", LanguageTag: code,
			DisplayLanguageName: LanguageName(code), IsAutoGenerated: strings.HasPrefix(vss, "a.")})
	}
	return out
}

// LanguageName is the language named in itself ("français" for fr), like Locale.getDisplayName(locale).
func LanguageName(code string) string {
	tag, err := language.Parse(code)
	if err != nil {
		return code
	}
	if n := display.Self.Name(tag); n != "" {
		return n
	}
	return code
}

func parseNext(w *Watch, n map[string]any, now time.Time) {
	results := List(n, "contents", "twoColumnWatchNextResults", "results", "results", "contents")
	for _, r := range results {
		if pri := Obj(r, "videoPrimaryInfoRenderer"); pri != nil {
			if w.LikeCount < 0 {
				w.LikeCount = likesFromPrimary(pri)
			}
		}
		if sec := Obj(r, "videoSecondaryInfoRenderer"); sec != nil {
			owner := Obj(sec, "owner", "videoOwnerRenderer")
			w.UploaderAvatarURL = LastURL(List(owner, "thumbnail", "thumbnails"))
			if v, ok := MixedNumber(Text(owner["subscriberCountText"])); ok {
				w.Subscribers = v
			}
			for _, b := range List(owner, "badges") {
				s := Str(b, "metadataBadgeRenderer", "style")
				if strings.Contains(s, "VERIFIED") {
					w.Verified = true
				}
			}
			w.License = "YouTube license"
			if row := Obj(sec, "metadataRowContainer", "metadataRowContainerRenderer", "rows", 0, "metadataRowRenderer"); row != nil {
				if Text(row["title"]) == "Licence" {
					if l := Text(Dig(row, "contents", 0)); l != "" {
						w.License = l
					}
				}
			}
		}
	}
	for _, p := range List(n, "engagementPanels") {
		panel := Obj(p, "engagementPanelSectionListRenderer")
		if Str(panel, "panelIdentifier") != "engagement-panel-macro-markers-description-chapters" {
			continue
		}
		for _, c := range List(panel, "content", "macroMarkersListRenderer", "contents") {
			m := Obj(c, "macroMarkersListItemRenderer")
			start, ok := Num(m, "onTap", "watchEndpoint", "startTimeSeconds")
			title := Text(m["title"])
			if !ok || title == "" || int64(start) > w.Duration {
				continue
			}
			u := WatchURL(w.ID) + "?t=" + strconv.Itoa(int(start))
			ch := Chapter{Title: title, StartTimeSeconds: int(start), URL: &u}
			if prev := LastURL(List(m, "thumbnail", "thumbnails")); prev != "" {
				ch.PreviewURL = &prev
			}
			w.Chapters = append(w.Chapters, ch)
		}
	}
	items := List(n, "contents", "twoColumnWatchNextResults", "secondaryResults", "secondaryResults", "results")
	for _, it := range items {
		if l := Obj(it, "lockupViewModel"); l != nil {
			if v, ok := FromLockup(l, now); ok {
				w.Related = append(w.Related, v)
			}
		} else if cv := Obj(it, "compactVideoRenderer"); cv != nil {
			if v, ok := FromVideoRenderer(cv, now); ok {
				w.Related = append(w.Related, v)
			}
		} else if t := Str(it, "continuationItemRenderer", "continuationEndpoint", "continuationCommand", "token"); t != "" {
			w.RelatedContinuation = t
		}
	}
}

func likesFromPrimary(pri map[string]any) int64 {
	for _, b := range List(pri, "videoActions", "menuRenderer", "topLevelButtons") {
		vm := Obj(b, "segmentedLikeDislikeButtonViewModel", "likeButtonViewModel", "likeButtonViewModel", "toggleButtonViewModel",
			"toggleButtonViewModel", "defaultButtonViewModel", "buttonViewModel")
		if label := Str(vm, "accessibilityText"); label != "" {
			if n := Digits(label); n > 0 {
				return n
			}
		}
		if t := Str(vm, "title"); t != "" {
			if n, ok := MixedNumber(t); ok {
				return n
			}
		}
	}
	return -1
}
